export function normalizeLanguage(language) {
  return language === "hi" ? "hi" : "en";
}

export function translate(language, key, variables = {}) {
  const selected = translations[normalizeLanguage(language)];
  const fallback = translations.en;
  const getValue = (source) => key.split(".").reduce((value, part) => value?.[part], source);
  let value = getValue(selected) ?? getValue(fallback) ?? key;
  if (Array.isArray(value)) return value;
  if (typeof value !== "string") return key;
  return value.replace(/\{(\w+)\}/g, (_, name) => variables[name] ?? `{${name}}`);
}

export default translations;
